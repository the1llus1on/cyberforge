"""One developer-owned renderer; escaped text and finite CSS choices only."""

from dataclasses import dataclass
from html import escape

from cyberforge.web.contracts import WebPageV2

CSP = (
    "default-src 'none'; script-src 'none'; style-src 'unsafe-inline'; "
    "img-src 'none'; font-src 'none'; connect-src 'none'; frame-src 'none'; "
    "object-src 'none'; base-uri 'none'; form-action 'none'"
)
THEME_COLORS = {
    "academic": ("#214e77", "#edf2f6", "Georgia, serif"),
    "corporate": ("#293e61", "#eef0f4", "Arial, sans-serif"),
    "service": ("#147569", "#eff7f4", "Arial, sans-serif"),
}
BASE_CSS = """
* {box-sizing:border-box} body {margin:0;background:var(--bg);color:var(--ink);
font:15px/1.55 Arial,sans-serif} main {max-width:var(--width);margin:auto;padding:28px}
section {margin:0 0 20px;padding:24px;background:var(--surface);border-radius:10px;
border:1px solid var(--line);overflow-wrap:anywhere} h1,h2,h3,p {margin:0 0 12px}
h1,h2 {font-family:var(--heading)} h1 {font-size:32px;line-height:1.2}
h2 {font-size:23px} h3 {font-size:17px} p {white-space:pre-wrap}
.header {border:0;border-bottom:3px solid var(--accent);border-radius:0}
.hero {padding:36px;background:var(--accent);color:#fff}
.cards-grid {display:grid;grid-template-columns:repeat(auto-fit,minmax(190px,1fr));
gap:14px}
article {padding:18px;border:1px solid var(--line);border-radius:8px}
.notice {border-left:5px solid var(--accent)}
.footer {background:transparent;font-size:12px}
.actions-row {display:flex;gap:12px;flex-wrap:wrap;margin-top:14px}
a {display:inline-block;background:var(--accent);color:white;text-decoration:none;
padding:10px 18px;border-radius:6px;font-weight:600}
.hero a {background:#fff;color:#253a56}
a:focus {outline:3px solid #e6ac33;outline-offset:3px}
.field {display:block;margin:12px 0;max-width:430px}
input {display:block;width:100%;padding:11px;border:1px solid var(--line);
border-radius:5px;background:var(--bg);color:var(--ink)}
.compact {padding:14px} .emphasis {border:2px solid var(--accent)}
.document-icon {font-size:32px} .hint {font-size:12px;opacity:.8}
@media(max-width:640px) {main {padding:14px} section,.hero {padding:18px}
h1 {font-size:26px}}
"""


@dataclass(frozen=True)
class RenderedPage:
    html: str
    css: str


def action_url(nonce: str, component: str, action: str) -> str:
    return f"cyberforge://action/{nonce}/{component}/{action}"


def render_page(page: WebPageV2, *, nonce: str = "inspection") -> RenderedPage:
    page = WebPageV2.model_validate_json(page.model_dump_json())
    # nonce is generated by trusted application code; validate even internal calls.
    from cyberforge.agents.contracts import resource_id

    resource_id(nonce)
    accent, background, heading = THEME_COLORS[page.theme]
    dark = page.color_mode == "dark"
    palette = dict(
        bg="#17202c" if dark else background,
        ink="#edf2f7" if dark else "#223249",
        surface="#243040" if dark else "#ffffff",
        line="#425064" if dark else "#d6dfe6",
        accent=accent,
        heading=heading,
        width={"standard": "1000px", "wide": "1300px", "centered": "760px"}[
            page.layout
        ],
    )
    css = (
        ":root {"
        + ";".join(f"--{k}:{v}" for k, v in palette.items())
        + "}\n"
        + BASE_CSS
    )
    output = []
    for c in page.components:
        title = f"<h2>{escape(c.title)}</h2>" if hasattr(c, "title") else ""
        body = f"<p>{escape(c.text)}</p>" if hasattr(c, "text") else ""
        if c.type == "hero":
            title = f"<h1>{escape(c.title)}</h1>"
        if c.type == "cards":
            body = (
                '<div class="cards-grid">'
                + "".join(
                    f"<article><h3>{escape(item.title)}</h3><p>{escape(item.text)}</p></article>"
                    for item in c.items
                )
                + "</div>"
            )
        if c.type == "document":
            title = '<span class="document-icon" aria-hidden="true">▤</span>' + title
        if c.type == "form":
            # Fixed readonly values prevent arbitrary credential entry.
            body += '<div role="group" aria-label="Синтетична навчальна форма">'
            for f in c.fields:
                value = (
                    "Підтверджено (демо)"
                    if f.kind == "confirmation"
                    else "demo-student"
                )
                body += (
                    f'<label class="field">{escape(f.label)}'
                    f'<input readonly autocomplete="off" value="{value}"></label>'
                )
            body += (
                '<p class="hint">Лише синтетичні значення. '
                "Справжні дані не вводяться.</p></div>"
            )
        actions = getattr(c, "actions", ())
        if actions:
            body += (
                '<div class="actions-row">'
                + "".join(
                    f'<a href="{escape(action_url(nonce, c.id, a.id), quote=True)}">'
                    f"{escape(a.label)}</a>"
                    for a in actions
                )
                + "</div>"
            )
        output.append(
            f'<section id="{escape(c.id, quote=True)}" '
            f'class="{c.type} {c.variant}">{title}{body}</section>'
        )
    html = (
        '<!doctype html><html lang="uk"><head><meta charset="utf-8">'
        '<meta http-equiv="Content-Security-Policy" '
        f'content="{escape(CSP, quote=True)}">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        f"<title>{escape(page.tab_title)}</title><style>{css}</style></head>"
        "<body><main>" + "".join(output) + "</main></body></html>"
    )
    return RenderedPage(html, css)
